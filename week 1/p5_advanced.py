# ============================================================
# Задача 1. Размен монет
# ============================================================
# Условие:
#   Дана сумма S и набор номиналов монет. Требуется выдать
#   сумму минимальным количеством монет.
#
# Жадная стратегия:
#   1) взять самую крупную монету, не превышающую остаток;
#   2) вычесть её из суммы;
#   3) повторять до нуля.
#
# Пример:
#   S = 87, coins = [50, 10, 5, 1]
#   Ответ: 7 монет (50 + 10 + 10 + 10 + 5 + 1 + 1)
#
# Сложность: O(k log k + n), где k — число номиналов,
#            n — количество монет в ответе.

def min_coins(amount: int, coins: list) -> int:
    """Вернуть минимальное число монет или -1, если нельзя."""
    count = 0

    while amount > 0:
        for coin in coins:
            if coin <= amount:
                amount -= coin
                count += 1
                break
        else:
            return -1
    return count


# ============================================================
# Задача 2. Выбор интервалов
# ============================================================
# Условие:
#   Даны интервалы времени. Нужно выбрать максимальное
#   количество непересекающихся интервалов.
#
# Жадная стратегия:
#   1) отсортировать интервалы по времени окончания;
#   2) брать интервал, если он начинается не раньше
#      окончания предыдущего.
#
# Пример:
#   intervals = [(1,4),(3,5),(0,6),(5,7),(3,9),(5,9),(6,10),(8,11)]
#   Ответ: 4
#
# Сложность: O(n log n).

def max_intervals(intervals: list) -> int:
    """Вернуть максимальное число непересекающихся интервалов."""
    intervals = sorted(intervals, key=lambda interval: interval[1])
    count = 0
    last_end = None
    
    for interval in intervals:
        if last_end is None or interval[0] >= last_end:
            count += 1
            last_end = interval[1]
    
    return count

# ============================================================
# Задача 3. Дробный рюкзак
# ============================================================
# Условие:
#   Есть рюкзак вместимостью W и предметы с весом wi и
#   стоимостью vi. Можно брать части предметов.
#   Максимизировать суммарную стоимость.
#
# Жадная стратегия:
#   1) вычислить удельную стоимость vi/wi;
#   2) сортировать по убыванию;
#   3) брать предметы, пока есть место;
#   4) последний предмет — частично.
#
# Сложность: O(n log n).

def fractional_knapsack(capacity: float, items: list) -> float:
    """
    items: список кортежей (weight, value).
    Вернуть максимальную суммарную стоимость.
    """
    items = sorted(items, key=lambda item: item[1] / item[0], reverse=True)

    remaining_capacity = capacity
    total_value = 0

    for item in items:
        weight = item[0]
        value = item[1]
        if weight <= remaining_capacity:
            total_value += value
            remaining_capacity -= weight
        else:
            fraction = remaining_capacity / weight
            total_value += value * fraction
            remaining_capacity = 0
            break
    
    return total_value


# ============================================================
# Задача 4. Минимальное число платформ
# ============================================================
# Условие:
#   Даны время прибытия и отправления поездов на станции
#   (в минутах от начала суток). Определите минимальное
#   количество платформ, чтобы все поезда могли остановиться.
#
# Пример:
#   arrivals   = [900, 940, 950, 1100, 1500, 1800]
#   departures = [910, 1200, 1120, 1130, 1900, 2000]
#   Ответ: 3
#
# Жадная идея:
#   отсортировать события: прибытие — +1, отправление — -1.
#   Пройти по событиям, поддерживая текущее число занятых
#   платформ и максимум за всё время.
#
# Вопрос: почему при равном времени прибытия и отправления
#   отправление должно обрабатываться раньше прибытия?
#
# Сложность: O(n log n), память O(n).

def min_platforms(arrivals: list, departures: list) -> int:
    """Вернуть минимальное число платформ."""

    events = []
    for arrival in arrivals:
        events.append((arrival, 1))

    for departure in departures:
        events.append((departure, -1))

    events.sort()

    current_platforms = 0
    max_platforms = 0

    for time, change in events:
        current_platforms += change
        max_platforms = max(max_platforms, current_platforms)

    return max_platforms


